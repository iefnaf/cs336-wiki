import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const book = JSON.parse(await fs.readFile(path.join(root,'book.json'),'utf8'));
const base = process.env.QA_BASE_URL || process.argv[3] || 'http://127.0.0.1:3360';
const browser = await chromium.launch({headless:true, ...(process.argv[2] ? {executablePath:process.argv[2]} : {})});
const errors = [];
const failures = [];
const context = await browser.newContext({viewport:{width:1440,height:1000}});
await context.route('https://giscus.app/client.js',r=>r.fulfill({contentType:'application/javascript',body:'/* Embedded discussion UI is checked separately by qa-comments.mjs. */'}));
const page = await context.newPage();
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=400&&!r.url().endsWith('/not-a-real-chapter/')) failures.push({url:r.url(),status:r.status()});});
try {
  await page.goto(base,{waitUntil:'networkidle'});
  await page.screenshot({path:root+'/artifacts/home-desktop.png'});
  assert.equal(await page.locator('.contents-row').count(),25);
  await page.locator('.sidebar .search-trigger').click();
  await page.locator('#search-input').fill('train_bpe');
  await page.waitForSelector('.search-result');
  assert((await page.locator('#search-results').textContent()).includes('训练'));
  await page.locator('#search-input').press('Enter');
  await page.waitForURL('**/assignment1/bpe-experiments/#train_bpe');
  assert(await page.locator('#train_bpe').isVisible());
  await page.locator('.topbar .theme-toggle').click();
  const dark = await page.locator('html').getAttribute('data-theme');
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('html').getAttribute('data-theme'),dark);
  await page.screenshot({path:root+'/artifacts/reading-dark.png'});
  if(dark==='dark') await page.locator('.topbar .theme-toggle').click();
  for (const c of book.chapters) {
    await page.goto(base+'/assignment1/'+c.slug+'/',{waitUntil:'networkidle'});
    assert.equal(await page.locator('h1').count(),1,c.slug+' h1');
    assert.equal(await page.locator('.original').count(),1,c.slug+' original');
    assert.equal(await page.locator('.katex-error').count(),0,c.slug+' math');
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Desktop overflow: '+c.slug);
  }
  await page.goto(base+'/assignment1/rmsnorm-swiglu/',{waitUntil:'networkidle'});
  await page.locator('#original summary').click();
  assert(await page.locator('#original pre').isVisible());
  await page.locator('#original summary').click();
  await page.screenshot({path:root+'/artifacts/reading-desktop.png'});
  await page.evaluate(()=>window.scrollTo({top:1000,behavior:'instant'}));
  await page.waitForTimeout(400);
  await page.goto(base,{waitUntil:'networkidle'});
  assert(await page.locator('.continue-link').isVisible());
  await page.locator('.continue-link').click();
  await page.waitForLoadState('networkidle');
  assert(await page.evaluate(()=>scrollY)>500,'Reading position was not restored');
  await page.goto(base+'/assignment1/rope/',{waitUntil:'networkidle'});
  await page.screenshot({path:root+'/artifacts/math-desktop.png',fullPage:true});
  const mobileContext = await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
  await mobileContext.route('https://giscus.app/client.js',r=>r.fulfill({contentType:'application/javascript',body:'/* Embedded discussion UI is checked separately by qa-comments.mjs. */'}));
  const mobile = await mobileContext.newPage();
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto(base,{waitUntil:'networkidle'});
  await mobile.screenshot({path:root+'/artifacts/home-mobile.png',fullPage:true});
  await mobile.locator('.menu-toggle').click();
  assert.equal(await mobile.locator('.menu-toggle').getAttribute('aria-expanded'),'true');
  await mobile.locator('.sidebar a[href="/assignment1/attention/"]').click();
  await mobile.waitForURL('**/assignment1/attention/');
  await mobile.screenshot({path:root+'/artifacts/reading-mobile.png',fullPage:true});
  for (const c of book.chapters) {
    await mobile.goto(base+'/assignment1/'+c.slug+'/',{waitUntil:'domcontentloaded'});
    assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile overflow: '+c.slug);
  }
  await mobile.goto(base+'/assignment1/modules/',{waitUntil:'networkidle'});
  await mobile.locator('.mobile-header .search-trigger').click();
  await mobile.locator('#search-input').fill('检查点');
  await mobile.waitForSelector('.search-result');
  assert((await mobile.locator('.search-result').first().textContent()).includes('检查点'));
  await mobile.screenshot({path:root+'/artifacts/search-mobile.png'});
  const missing = await page.goto(base+'/not-a-real-chapter/');
  assert.equal(missing.status(),404);
  assert.equal(errors.length,0,'Browser errors: '+JSON.stringify(errors));
  assert.equal(failures.length,0,'Resource failures: '+JSON.stringify(failures));
  const result={base,desktop_pages:25,mobile_pages:25,checks:['Search by exercise ID and Chinese text','Keyboard search navigation','Theme persistence','Mobile navigation','English original disclosure','Continue reading and position restore','Rendered math','No page overflow','404 status','No browser errors or failed resources'],errors,failures};
  await fs.writeFile(root+'/artifacts/browser-qa.json',JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
} finally { await browser.close(); }
