import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = process.argv[3] || 'http://127.0.0.1:3360';
const browser = await chromium.launch({headless:true,...(process.argv[2]?{executablePath:process.argv[2]}:{})});
const errors = [];
const context = await browser.newContext({viewport:{width:1440,height:1000}});
await context.route('https://github.com/iefnaf/cs336-wiki/issues/new**',route=>route.fulfill({status:200,contentType:'text/html',body:'<!doctype html><title>Issue draft target</title>'}));
const page = await context.newPage();
page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto(base+'/assignment1/rope/',{waitUntil:'networkidle'});
  const feedback = page.locator('.reader-tools .feedback-link');
  const fallback = new URL(await feedback.getAttribute('href'));
  assert.equal(fallback.searchParams.get('template'),'error-report.yml');
  assert(fallback.searchParams.get('version').includes('1.1.0'));
  assert.equal(fallback.searchParams.get('pdf_pages'),'22–23');
  assert(!fallback.searchParams.has('labels'));
  const selection = await page.locator('.prose > p').first().textContent();
  await page.locator('.prose > p').first().evaluate(el=>{
    const range=document.createRange();range.selectNodeContents(el);
    const selected=window.getSelection();selected.removeAllRanges();selected.addRange(range);
  });
  const popupPromise = context.waitForEvent('page');
  await feedback.click();
  const popup = await popupPromise;
  await popup.waitForURL('https://github.com/iefnaf/cs336-wiki/issues/new**');
  await popup.waitForLoadState('domcontentloaded');
  const draft = new URL(popup.url());
  assert.equal(draft.searchParams.get('excerpt'),selection.trim());
  assert.equal(draft.searchParams.get('page_url'),'https://cs336.wiki/assignment1/rope/#section-1');
  assert(draft.searchParams.get('chapter').includes('旋转位置嵌入'));
  await popup.close();
  await page.screenshot({path:root+'/artifacts/chapter-feedback-desktop.png'});
  await page.locator('#rope p').first().evaluate(el=>{
    el.textContent='选文测试 中文&符号 <tag> 😀 '.repeat(200);
    const range=document.createRange();range.selectNodeContents(el);
    const selected=window.getSelection();selected.removeAllRanges();selected.addRange(range);
  });
  await page.locator('.reader-support .feedback-link').scrollIntoViewIfNeeded();
  const longPopupPromise=context.waitForEvent('page');
  await page.locator('.reader-support .feedback-link').click();
  const longPopup=await longPopupPromise;
  await longPopup.waitForURL('https://github.com/iefnaf/cs336-wiki/issues/new**');
  await longPopup.waitForLoadState('domcontentloaded');
  const longDraft=new URL(longPopup.url());
  assert(longDraft.href.length<=7500,'Issue URL must stay within its length budget');
  assert(longDraft.searchParams.get('excerpt').includes('<tag> 😀'));
  assert(!longDraft.searchParams.get('excerpt').includes('\uFFFD'),'Selection must preserve Unicode boundaries');
  assert.equal(longDraft.searchParams.get('page_url'),'https://cs336.wiki/assignment1/rope/#rope');
  await longPopup.close();
  await page.goto(base+'/community/',{waitUntil:'networkidle'});
  assert.equal(await page.locator('.discussion-row').count(),25);
  assert.equal(await page.locator('.sidebar [aria-current="page"]').textContent(),'读者社区 ↗');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.screenshot({path:root+'/artifacts/community-desktop.png',fullPage:true});
  await page.locator('.topbar .theme-toggle').click();
  await page.screenshot({path:root+'/artifacts/community-dark.png'});
  const mobileContext=await browser.newContext({viewport:{width:390,height:844},isMobile:true});
  const mobile=await mobileContext.newPage();
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto(base+'/assignment1/rope/',{waitUntil:'networkidle'});
  assert(await mobile.locator('.reader-tools .feedback-link').isVisible());
  assert(await mobile.locator('.reader-tools .chapter-discussion').isVisible());
  await mobile.screenshot({path:root+'/artifacts/chapter-feedback-mobile.png'});
  await mobile.locator('.menu-toggle').click();
  await mobile.locator('.nav-community').click();
  await mobile.waitForURL('**/community/');
  assert.equal(await mobile.locator('.discussion-row').count(),25);
  assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await mobile.screenshot({path:root+'/artifacts/community-mobile.png',fullPage:true});
  assert.equal(errors.length,0,JSON.stringify(errors));
  const result={base,checks:['No-JavaScript feedback URL has chapter, source pages and versions','Selected text and section anchors carried into Issue form','Long Unicode selections stay intact within URL budget','Public-reader links require no label permission','25 chapter discussion links','Desktop/mobile community navigation','Dark and light community layout','No page overflow or script errors'],errors};
  await fs.writeFile(root+'/artifacts/community-qa.json',JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
} finally {await browser.close();}
